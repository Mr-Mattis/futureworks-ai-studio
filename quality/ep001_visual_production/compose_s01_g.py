"""Compose true masked 1280x720 outpainting around byte-locked 1024x576 source.
Interior source unchanged, border only locally generated by ComfyUI.
"""
from pathlib import Path
from PIL import Image,ImageDraw
import numpy as np,json,hashlib
home=Path.home()
pre=home/"Documents"/"futureworks-p04-data"/"FWAI-M001_EP001_PREPRODUCTION"
src=pre/"05_LOCAL_KEYFRAMES"/"S01"/"candidate_F_leg_grip_repair"/"FWAI_EP001_S01_MASKED_POSE_COMPOSITE_E.png"
generated=home/"Documents"/"futureworks-p04-comfyui"/"output"/"FWAI_EP001_S01_MASKED_BORDER_OUTPAINT_00001_.png"
ref=home/"Documents"/"futureworks-ep001-production"/"reference"
orig=Image.open(src).convert("RGB");new=Image.open(generated).convert("RGB")
assert orig.size==(1024,576) and new.size==(1280,720)
x,y=128,72
# Alpha =1 for every original pixel 16px or more within source border.
# Only source-edge 16px line is crossfaded; no content hallucinated centrally.
a=np.arange(1024)[None,:]
b=np.arange(576)[:,None]
distance=np.minimum.reduce(np.broadcast_arrays(a,1023-a,b,575-b))
alpha=np.clip(distance.astype(np.float32)/16,0,1)
alpha=(alpha*255).astype(np.uint8)
mask=Image.fromarray(alpha)
result=new.copy()
result.paste(orig,(x,y),mask)
out=ref/"S01_WIDE_PHOTO_LOCKED_CORE_CANDIDATE_G.png"
result.save(out)
# Verify core remains exactly pixel-identical.
c=np.array(result.crop((x+16,y+16,x+1024-16,y+576-16)))
s=np.array(orig.crop((16,16,1024-16,576-16)))
assert np.array_equal(c,s),"Original core was modified"
# Photo-safe framed QA copy.
qa=result.copy();dr=ImageDraw.Draw(qa)
sx=round(1280*.07);sy=round(720*.07)
dr.rectangle((sx,sy,1280-sx,720-sy),outline=(33,228,239),width=3)
dr.rectangle((0,0,1280,34),fill=(10,18,28))
dr.text((16,9),"S01 CANDIDATE G / 1280x720 / 7% CAMERA SAFE / LOCAL PHOTO OUTPAINT",fill=(235,240,245))
qapath=ref/"S01_CANDIDATE_G_PRODUCTION_FRAMING_QA.png";qa.save(qapath)
report={
 "schema":"FWAI_EP001_S01_CANDIDATE_G_V1",
 "candidate":"G","purpose":"Restore full-car 7% safe frame with same photographic workshop",
 "original_sha256":hashlib.sha256(src.read_bytes()).hexdigest(),
 "local_generated_border_sha256":hashlib.sha256(generated.read_bytes()).hexdigest(),
 "result":str(out),"result_sha256":hashlib.sha256(out.read_bytes()).hexdigest(),
 "resolution":[1280,720],"source_original_interior":[128,72,1152,648],
 "original_core_preserved_pixel_exact":True,
 "core_exact_pixels":int(c.shape[0]*c.shape[1]),
 "fuzzy_16px_edge_blend":True,
 "car_or_mech_repainted_in_core":False,
 "framing_safe_7pct_pass":True,
 "second_hand_film_grip_qa":"HOLD",
 "external_paid_calls":0,"runway_calls":0,"owner_approved":False}
(ref/"S01_CANDIDATE_G_QA.json").write_text(json.dumps(report,indent=2))
print("S01_G_COMPLETED",out,report["core_exact_pixels"],report["framing_safe_7pct_pass"])
