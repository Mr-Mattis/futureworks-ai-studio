"""P04 approval remediation: independently authenticated human signoff artifacts.

No signing keys or approvals are generated by this module. The trusted
operator-provisioned signing key stays outside Git and any workflow metadata.
Human acceptance is distinct from merge/development authorization.
"""
from __future__ import annotations
import hashlib
import hmac
import json
from pathlib import Path

from imaging_gate_support import canonical_bytes, Rejected


def verify_approval(approval_path, bundle_path, *, owner_key):
    """Only exact manifest + ten immutable image hashes can be approved."""
    if not isinstance(owner_key, bytes) or len(owner_key) < 32:
        raise Rejected("Strong owner-controlled verification key required")
    record = json.loads(Path(approval_path).read_text())
    expected_fields = {"project_id", "run_id", "manifest_sha256", "asset_sha256",
                       "decision", "rights_reviewed", "image_quality_reviewed",
                       "consistency_reviewed", "reviewer", "hmac_sha256"}
    if set(record) != expected_fields:
        raise Rejected("Incomplete or extra approval fields")
    if any(record.get(k) is not True for k in (
            "rights_reviewed", "image_quality_reviewed", "consistency_reviewed")):
        raise Rejected("Explicit human media/rights review required")
    if record["decision"] != "approved" or not isinstance(record["reviewer"], str):
        raise Rejected("Independent human approver decision required")
    if len(record["reviewer"].strip()) < 3:
        raise Rejected("Human approver identification required")
    payload = {k: v for k,v in record.items() if k != "hmac_sha256"}
    mac = hmac.new(owner_key, canonical_bytes(payload), hashlib.sha256).hexdigest()
    if not isinstance(record["hmac_sha256"], str) or not hmac.compare_digest(
            mac, record["hmac_sha256"]):
        raise Rejected("Approval signature invalid")
    bundle = json.loads(Path(bundle_path).read_text())
    if bundle.get("status") != "ready_for_visual_director" or len(bundle.get("assets",[])) != 10:
        raise Rejected("Ten indexed P04 assets required")
    if bundle.get("project_id") != record["project_id"] or bundle.get("run_id") != record["run_id"]:
        raise Rejected("Project/run identity changed")
    from pathlib import Path as P
    manifest = P(__file__).resolve().parents[2] / "contracts/production-manifest/v1.0.0/example.valid.json"
    if hashlib.sha256(manifest.read_bytes()).hexdigest() != record["manifest_sha256"]:
        raise Rejected("Canonical manifest byte identity changed")
    actual = sorted(a["sha256"] for a in bundle["assets"])
    if sorted(record["asset_sha256"]) != actual or len(set(actual)) != 10:
        raise Rejected("Asset provenance differs from reviewed images")
    if json.loads(manifest.read_text()).get("approval_state",{}).get("status") != "approved":
        raise Rejected("Immutable manifest has not been separately approved")
    return {"status":"verified_human_review", "project_id":record["project_id"],
            "run_id":record["run_id"], "asset_count":10,
            "rights_reviewed":True,"image_quality_reviewed":True,
            "consistency_reviewed":True,"production_approved":False,
            "spend_authorized":False,"publish_authorized":False}
